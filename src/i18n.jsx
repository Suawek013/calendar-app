const DICTIONARIES = { en: EN, pl: PL };

const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("cal_lang") || "en");

  useEffect(() => {
    localStorage.setItem("cal_lang", lang);
  }, [lang]);

  const t = (key, params = {}) => {
    const dict = DICTIONARIES[lang] || DICTIONARIES.en;
    let str = dict[key];
    if (!str) {
      console.warn(`Missing translation for key: ${key}`);
      return key; // fallback to key
    }
    // Replace {param} in string
    Object.keys(params).forEach(p => {
      str = str.replace(`{${p}}`, params[p]);
    });
    return str;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useTranslation() {
  return useContext(LanguageContext);
}

export function tStatic(key, params = {}) {
  const lang = localStorage.getItem("cal_lang") || "en";
  const dict = DICTIONARIES[lang] || DICTIONARIES.en;
  let str = dict[key];
  if (!str) {
    console.warn(`Missing translation for key: ${key}`);
    return key;
  }
  Object.keys(params).forEach(p => {
    str = str.replace(`{${p}}`, params[p]);
  });
  return str;
}
